import AppLog
import Foundation

/// Translates the chrome's `TerminalTheme` into ghostty config-file text — the seam's
/// theme vocabulary driving the libghostty backend, so the chrome stays the source of
/// truth for appearance on both backends. libghostty accepts configuration only from
/// files (no setter API), so `GhosttyApp` writes this text to a scratch file and loads
/// it; nothing here reads or touches any user-level ghostty config.
enum GhosttyConfigWriter {
    /// The full generated config: theme-derived colors and font, plus the terminal
    /// behavior (cursor shape/thickness, Option semantics) the chrome dials from user config.
    /// A nil `behavior` uses the shipped `TerminalBehavior.default`.
    static func configText(for theme: TerminalTheme?, behavior: TerminalBehavior? = nil) -> String {
        let behavior = behavior ?? .default
        var lines = [
            "# Generated by zen-term from the chrome's TerminalTheme — do not edit.",
            "cursor-style = \(behavior.ghosttyCursorStyle)",
            "cursor-style-blink = \(behavior.cursorBlink)",
            // Shell integration's cursor-shape-per-mode would override the block with a
            // bar at the prompt; keep the rest (cwd, prompt marking → isBusy) and let
            // cursor-style rule.
            "shell-integration-features = no-cursor",
            "mouse-hide-while-typing = true",
            "font-thicken = true",
            // Option acts as Alt/Meta — ⌥f/⌥b word-nav in readline, Meta chords in
            // vim/emacs — the terminal convention, chosen over macOS accent composing.
            "macos-option-as-alt = \(behavior.optionAsAlt)",
        ]
        // Widen the bar/underline cursor (ghostty's base is a nearly invisible 1px). A delta
        // from that base; the block cursor fills the cell and ignores it.
        if let delta = behavior.ghosttyCursorThicknessDelta {
            lines.append("adjust-cursor-thickness = \(delta)")
        }
        if let theme {
            lines.append("font-family = \(theme.fontName)")
            lines.append("font-size = \(theme.fontSize)")
            lines.append("background = \(theme.background.hex)")
            lines.append("foreground = \(theme.foreground.hex)")
            lines.append("cursor-color = \(theme.cursor.hex)")
            lines.append("selection-background = \(theme.selectionBackground.hex)")
            for (index, color) in theme.ansi.enumerated() {
                lines.append("palette = \(index)=\(color.hex)")
            }
        }
        // Custom shaders run as post-process passes, in order (ghostty's repeatable
        // `custom-shader`). Paths are already absolute (the chrome resolves bundled names), so
        // ghostty's file-relative resolution — which would look next to this temp config — never
        // applies. Pin `custom-shader-animation = true` so the effect animates while focused
        // regardless of ghostty's default drift; only emit it when there's a shader to animate.
        for shader in behavior.customShaders {
            lines.append("custom-shader = \(shader)")
        }
        if !behavior.customShaders.isEmpty {
            lines.append("custom-shader-animation = true")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// Write the generated config where libghostty can load it and return the path,
    /// or nil if the write failed (the caller falls back to ghostty's own defaults).
    /// The file lives for the process's lifetime — the OS reaps the temp directory.
    static func writeConfig(for theme: TerminalTheme?, behavior: TerminalBehavior? = nil) -> String? {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("zenterm-ghostty-config-\(ProcessInfo.processInfo.processIdentifier)")
        do {
            try configText(for: theme, behavior: behavior).write(to: url, atomically: true, encoding: .utf8)
            return url.path
        } catch {
            Log.error(
                "GhosttyConfigWriter: failed to write generated config: \(error)", category: .config)
            return nil
        }
    }
}

extension TerminalColor {
    /// `#rrggbb` — the color syntax ghostty's config parser accepts.
    var hex: String {
        String(format: "#%02x%02x%02x", red, green, blue)
    }
}
